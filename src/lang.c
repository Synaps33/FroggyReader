const char *eg_tr(int language, int id)
{
    if (language < 0 || language >= LANG_COUNT) language = LANG_EN;
    if (id < 0 || id >= L_COUNT) return "";
    const char *s = g_text[language][id];
    if (!s) s = g_text[LANG_EN][id];
    return s ? s : "";
}

const char *eg_language_name(int language)
{
    static const char *const names[LANG_COUNT] = {
        "English", "Polski", "Deutsch", "日本語"
    };
    if (language < 0 || language >= LANG_COUNT) language = LANG_EN;
    return names[language];
}
